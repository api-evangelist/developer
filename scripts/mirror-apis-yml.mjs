#!/usr/bin/env node
// Mirrors the API Evangelist provider profile (apis.yml) onto a host we control.
//
// The APIs.json index describing this provider is canonical in the
// api-evangelist/api-evangelist repo and was only ever reachable at
// raw.githubusercontent.com. That makes the catalog operator's own profile
// GitHub-hosted rather than self-hosted -- the same "described from the outside"
// posture we score other providers down for.
//
// Fetching at build time (rather than committing a copy) is deliberate: a
// checked-in duplicate drifts silently, and a stale profile is worse than none.
// The build is the sync. `x-canonical-profile` in the output names the source so
// the mirror can never be mistaken for the original.
//
// Note apievangelist.com/apis.yml is a DIFFERENT index (aid: posts, scoped to the
// website repo) -- this one belongs on the developer portal.

import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const CANONICAL =
  "https://raw.githubusercontent.com/api-evangelist/api-evangelist/refs/heads/main/apis.yml";
const OUT = join(root, "public", "apis.yml");
// Outside public/ on purpose — a fallback copy is build state, not a published document.
const FALLBACK = join(root, ".cache", "apis.yml.last");

const banner = (source) =>
  `# Mirror of the API Evangelist provider profile, served from the host we control.\n` +
  `# Canonical source: ${source}\n` +
  `# Regenerated by scripts/mirror-apis-yml.mjs on every portal build -- do not edit.\n`;

let body;
try {
  const res = await fetch(CANONICAL, { redirect: "follow" });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  body = await res.text();
  if (!body.includes("aid: api-evangelist")) {
    throw new Error("fetched document is not the api-evangelist profile");
  }
  mkdirSync(dirname(FALLBACK), { recursive: true });
  writeFileSync(FALLBACK, body, "utf8");
} catch (err) {
  // Never fail the portal build on a transient fetch error, but never publish a
  // silently-empty profile either: fall back to the last good copy or bail loudly.
  if (existsSync(FALLBACK)) {
    console.warn(`mirror-apis-yml: fetch failed (${err.message}) -- using last good copy`);
    body = readFileSync(FALLBACK, "utf8");
  } else {
    console.error(`mirror-apis-yml: fetch failed (${err.message}) and no fallback -- skipping`);
    process.exit(0);
  }
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, banner(CANONICAL) + body, "utf8");
console.log(`mirror-apis-yml: wrote ${OUT} (${body.length} bytes)`);
